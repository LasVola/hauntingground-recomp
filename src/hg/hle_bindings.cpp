        // Equivalent of the recompiler's generated stub body: return to $ra unless the handler redirects.
        // The dispatcher has set ctx->pc to the called address, which names the SDK function for tracing.
        template <PS2Runtime::RecompiledFunction Handler>
        void hleTrampoline(uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime)
        {
            if (log::traceEnabled(log::Category::Hook))
                traceCall(ctx);
            ctx->pc = getRegU32(ctx, 31);
            Handler(rdram, ctx, runtime);
            if (log::traceEnabled(log::Category::Hook))
                HG_TRACE(Hook, "    -> v0=0x" << std::hex << getRegU32(ctx, 2));
        }

        // ---- sceSifLoadStartModule / sceSifLoadStartModuleBuffer (SDK 3.0.2 loadfile) ------------------------------
        // Haunting Ground loads its 12 disc IRX through sceSifLoadModule 0x2753A0 or, when the caller wants module_start's
        // result, through 0x2753C0 (Iop_LoadModule 0x1BC0F0 picks by its result pointer), and the embedded ck01 IRX through
        // 0x275158 (Iop_LoadEmbeddedModule 0x37E1F0). Both are the SDK wrappers of sceSifLoadModule / sceSifLoadModuleBuffer
        // that pass the caller's `int *result` (a3) to the loadfile RPC worker instead of a local. Left recompiled they
        // would bind the loadfile server 0x80000006 (0x2749A0), which the runtime does not serve, and retry forever. The
        // runtime has no handler of this name (ps2_call_list.h), so these use its IOP module loader directly and store
        // the module's real module_start return value in *result, as the IOP loadfile server does. Game_Init 0x2D1E40
        // exits when ck01's (result & ~3) is not 0, so *result must be the real value, never a guess.
        // If a later runtime gains handlers of these names, those are used instead (see installHleBindings).
        constexpr uint32_t kMaxModulePathBytes = 252u;           // loadfile's path field (SDK LF_PATH_MAX)
        constexpr uint32_t kMaxModuleArgumentBytes = 64u * 1024u; // same bound the runtime's SifLoadModule uses

        bool readGuestString(const uint8_t *rdram, uint32_t address, uint32_t maxBytes, std::string &out)
        {
            out.clear();
            for (uint32_t i = 0; i < maxBytes; ++i)
            {
                const uint8_t *byte = getConstMemPtr(rdram, address + i);
                if (!byte)
                    return false;
                if (*byte == 0u)
                    return true;
                out.push_back(static_cast<char>(*byte));
            }
            return true; // unterminated: cut at maxBytes, as the runtime's bounded reader does
        }

        bool readGuestBytes(const uint8_t *rdram, uint32_t address, uint32_t size, std::vector<uint8_t> &out)
        {
            out.clear();
            if (size == 0u || address == 0u)
                return true;
            if (size > kMaxModuleArgumentBytes)
                return false;
            out.resize(size);
            for (uint32_t i = 0; i < size; ++i)
            {
                const uint8_t *byte = getConstMemPtr(rdram, address + i);
                if (!byte)
                    return false;
                out[i] = *byte;
            }
            return true;
        }

        // v0 = module id (or -1); *result = module_start's return value when the module was loaded and started.
        void finishLoadStart(uint8_t *rdram, R5900Context *ctx, const ps2x::iop::ModuleLoadResult &loaded, uint32_t resultAddress,
                             std::string_view api, const std::string &what)
        {
            const bool ok = loaded.handled && loaded.moduleId > 0;
            if (ok && resultAddress != 0u)
            {
                if (uint8_t *result = getMemPtr(rdram, resultAddress))
                {
                    const int32_t value = loaded.startResult;
                    std::memcpy(result, &value, sizeof(value));
                }
            }
            static std::atomic<uint32_t> logged{0u};
            if (ok || logged.fetch_add(1u) < 32u)
            {
                HG_INFO(Iop, api << " " << what << " -> id " << loaded.moduleId << ", module_start " << loaded.startResult
                                 << (resultAddress ? "" : " (no result pointer)") << (ok ? "" : " FAILED"));
            }
            setReturnS32(ctx, ok ? loaded.moduleId : -1);
        }

        // int sceSifLoadStartModule(const char *path, int arglen, const char *args, int *result)
        void sifLoadStartModule(uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime)
        {
            const uint32_t pathAddress = getRegU32(ctx, 4);
            const uint32_t argumentSize = getRegU32(ctx, 5);
            const uint32_t argumentAddress = getRegU32(ctx, 6);
            const uint32_t resultAddress = getRegU32(ctx, 7);
            std::string path;
            std::vector<uint8_t> arguments;
            if (!runtime || !readGuestString(rdram, pathAddress, kMaxModulePathBytes, path) || path.empty() ||
                !readGuestBytes(rdram, argumentAddress, argumentSize, arguments))
            {
                HG_ERROR(Iop, "sceSifLoadStartModule: unreadable path 0x" << std::hex << pathAddress << " or arguments 0x"
                                                                          << argumentAddress << "+" << std::dec << argumentSize);
                setReturnS32(ctx, -1);
                return;
            }
            const ps2x::iop::ModuleLoadResult loaded =
                runtime->loadIopModule(path, arguments.empty() ? nullptr : arguments.data(), static_cast<uint32_t>(arguments.size()));
            finishLoadStart(rdram, ctx, loaded, resultAddress, "sceSifLoadStartModule", path);
        }

        // int sceSifLoadStartModuleBuffer(const void *iop_addr, int arglen, const char *args, int *result): the module
        // image is already in IOP RAM (the game copies it there with sceSifSetDma first).
        void sifLoadStartModuleBuffer(uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime)
        {
            const uint32_t bufferAddress = getRegU32(ctx, 4);
            const uint32_t argumentSize = getRegU32(ctx, 5);
            const uint32_t argumentAddress = getRegU32(ctx, 6);
            const uint32_t resultAddress = getRegU32(ctx, 7);
            std::vector<uint8_t> arguments;
            if (!runtime || bufferAddress == 0u || !readGuestBytes(rdram, argumentAddress, argumentSize, arguments))
            {
                HG_ERROR(Iop, "sceSifLoadStartModuleBuffer: bad buffer 0x" << std::hex << bufferAddress << " or arguments 0x"
                                                                           << argumentAddress << "+" << std::dec << argumentSize);
                setReturnS32(ctx, -1);
                return;
            }
            const ps2x::iop::ModuleLoadResult loaded = runtime->loadIopModuleBuffer(
                bufferAddress, arguments.empty() ? nullptr : arguments.data(), static_cast<uint32_t>(arguments.size()));
            std::ostringstream what;
            what << "iop:0x" << std::hex << bufferAddress;
            finishLoadStart(rdram, ctx, loaded, resultAddress, "sceSifLoadStartModuleBuffer", what.str());
        }

